export function getLocalizedProgramIntelligence(
  programCode: string,
  language: Language,
  fallbackData: AcademicProgramIntelligence
): AcademicProgramIntelligence {
  if (language === 'EN') return fallbackData;

  const overlay = PROGRAM_INTELLIGENCE_TA[programCode];
  if (!overlay) return fallbackData;

  return {
    ...fallbackData,
    title: overlay.title || fallbackData.title,
    shortName: overlay.shortName || fallbackData.shortName,
    badge: overlay.badge || fallbackData.badge,
    targetAudience: overlay.targetAudience || fallbackData.targetAudience,
    headline: overlay.headline || fallbackData.headline,
    heroBranding: overlay.heroBranding
      ? { ...fallbackData.heroBranding, ...overlay.heroBranding }
      : fallbackData.heroBranding,
    introduction: overlay.introduction
      ? { ...fallbackData.introduction, ...overlay.introduction }
      : fallbackData.introduction,
    examination: {
      ...fallbackData.examination,
      conductingAuthority:
        overlay.examinationOverrides?.conductingAuthority ||
        fallbackData.examination.conductingAuthority,
      annualCadence:
        overlay.examinationOverrides?.annualCadence ||
        fallbackData.examination.annualCadence,
      examMode:
        overlay.examinationOverrides?.examMode ||
        fallbackData.examination.examMode,
      negativeMarkingRule:
        overlay.examinationOverrides?.negativeMarkingRule ||
        fallbackData.examination.negativeMarkingRule,
      stages:
        overlay.examStages && overlay.examStages.length > 0
          ? fallbackData.examination.stages.map((stage, idx) => {
              const ov = overlay.examStages?.[idx];
              if (!ov) return stage;
              return {
                ...stage,
                name: ov.name,
                nature: ov.nature,
                description: ov.description,
              };
            })
          : fallbackData.examination.stages,
    },
    marksDistribution: {
      ...fallbackData.marksDistribution,
      overview: overlay.marksDistributionOverview || fallbackData.marksDistribution.overview,
      rows:
        overlay.marksDistributionRows && overlay.marksDistributionRows.length > 0
          ? fallbackData.marksDistribution.rows.map((row, idx) => {
              const ov = overlay.marksDistributionRows?.[idx];
              if (!ov) return row;
              return {
                ...row,
                subject: ov.subject,
                section: ov.section || row.section,
                highYieldWeightage: ov.highYieldWeightage,
              };
            })
          : fallbackData.marksDistribution.rows,
    },
    eligibilityAndCutoffs: {
      ...fallbackData.eligibilityAndCutoffs,
      cutoffsDistinctionExplanation:
        'முக்கிய வேறுபாடு: "தகுதி கட்-ஆஃப் விழுக்காடு" என்பது கலந்தாய்வில் பங்கேற்க மட்டுமே தகுதி அளிக்கும்; அது சேர்க்கையை உறுதி செய்யாது. முதன்மை அரசு கல்லூரியில் சேர்க்கை பெற "பாதுகாப்பான சேர்க்கை மதிப்பெண்" (Seat Allotment Safe Score) பெறுவது இன்றியமையாதது.',
      officialStatutoryNote:
        'அதிகாரப்பூர்வ சட்டப்பூர்வ குறிப்பு: அனைத்து இடஒதுக்கீடு விழுக்காடுகளும் மற்றும் வயது வரம்புகளும் சம்பந்தப்பட்ட மத்திய/மாநில அரசு தேர்வு வாரிய விதிமுறைகளின்படி சரிபார்க்கப்பட்டன.',
      categories:
        overlay.eligibilityCategories && overlay.eligibilityCategories.length > 0
          ? fallbackData.eligibilityAndCutoffs.categories.map((cat, idx) => {
              const ov = overlay.eligibilityCategories?.[idx];
              if (!ov) return cat;
              return {
                ...cat,
                categoryName: ov.categoryName,
                qualifyingCriteria: ov.qualifyingCriteria,
                typicalAllotmentSafeScore: ov.typicalAllotmentSafeScore,
                maxAttemptsOrAge: ov.maxAttemptsOrAge,
              };
            })
          : fallbackData.eligibilityAndCutoffs.categories,
    },
    curriculum:
      overlay.curriculum && overlay.curriculum.length > 0
        ? overlay.curriculum
        : fallbackData.curriculum,
    studentApproach:
      overlay.studentApproach && overlay.studentApproach.length > 0
        ? fallbackData.studentApproach.map((pillar, idx) => {
            const ov = overlay.studentApproach?.[idx];
            if (!ov) return pillar;
            return {
              ...pillar,
              title: ov.title,
              tagline: ov.tagline,
              description: ov.description,
            };
          })
        : fallbackData.studentApproach,
    careerOpportunities:
      overlay.careerOpportunities && overlay.careerOpportunities.length > 0
        ? fallbackData.careerOpportunities.map((career, idx) => {
            const ov = overlay.careerOpportunities?.[idx];
            if (!ov) return career;
            return {
              ...career,
              roleOrDegree: ov.roleOrDegree,
              institutionOrCadre: ov.institutionOrCadre,
              description: ov.description,
              futureScope: ov.futureScope,
            };
          })
        : fallbackData.careerOpportunities,
    faqs:
      overlay.faqs && overlay.faqs.length > 0
        ? overlay.faqs
        : fallbackData.faqs,
  };
}
